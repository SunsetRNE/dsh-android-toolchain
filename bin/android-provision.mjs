#!/usr/bin/env node
/**
 * Provision the shared area from `toolchain.manifest.json`.
 *
 * "Installing the plugin installs the build components": the package's
 * `postinstall` runs `--auto` (skip with DSH_ANDROID_PROVISION=off or in CI),
 * which installs the launchers immediately and downloads the enabled
 * components. Everything is idempotent and pinned by sha256.
 *
 * usage:
 *   android-provision                 # install enabled components
 *   android-provision --dry-run       # plan only
 *   android-provision --component jdk # one component
 *   android-provision --root /path --register   # second root, remembered by label
 *   android-provision --root /path --reuse-from default   # reuse another root's archives
 *   android-provision --pin           # print sha256 for enabled sources
 *   android-provision --pin --write   # write them into the repo manifest
 *   android-provision --verify-manifest [--strict]
 */
import { spawnSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { chmodSync, copyFileSync, createReadStream, createWriteStream, existsSync, mkdirSync, readFileSync, readdirSync, renameSync, rmSync, statSync, symlinkSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { Readable } from 'node:stream'
import { pipeline } from 'node:stream/promises'
import { fileURLToPath } from 'node:url'
import { MANIFEST_PATH, enabledComponents, loadManifest, probeSources, validateManifest } from '../src/manifest.mjs'
import { binPath, currentPath, installedMarker, isInstalledCopy, resolveRoot } from '../src/paths.mjs'
import { registerRoot, resolveRootRef } from '../src/roots.mjs'

const PKG_DIR = fileURLToPath(new URL('..', import.meta.url))
const PKG = JSON.parse(readFileSync(join(PKG_DIR, 'package.json'), 'utf8'))
const LAUNCHER_TAG = '# generated by dsh-android-toolchain'

const argv = process.argv.slice(2)
const has = (flag) => argv.includes(flag)
const value = (flag) => {
  const index = argv.indexOf(flag)
  return index < 0 ? undefined : argv[index + 1]
}
const MANIFEST = value('--manifest')
const load = () => loadManifest(MANIFEST ?? MANIFEST_PATH)
const values = (flag) => {
  const out = []
  argv.forEach((item, index) => {
    if (item === flag && argv[index + 1]) out.push(argv[index + 1])
  })
  return out
}

const log = (message) => console.log(`[android-toolchain] ${message}`)

function fail(message) {
  console.error(`[android-toolchain] ${message}`)
  process.exit(1)
}

async function sha256(file) {
  const hash = createHash('sha256')
  await pipeline(createReadStream(file), hash)
  return hash.digest('hex')
}

async function download(url, destination) {
  const response = await fetch(url, { redirect: 'follow' })
  if (!response.ok || !response.body) throw new Error(`HTTP ${response.status} for ${url}`)
  const hash = createHash('sha256')
  const counters = { bytes: 0 }
  await pipeline(
    Readable.fromWeb(response.body),
    async function* (source) {
      for await (const chunk of source) {
        hash.update(chunk)
        counters.bytes += chunk.length
        yield chunk
      }
    },
    createWriteStream(destination),
  )
  return { sha256: hash.digest('hex'), bytes: counters.bytes }
}

// python3 -m zipfile drops the executable bit, which breaks gradle/bin/* and
// every JDK tool in a zip. This variant restores the mode from external_attr.
const ZIP_PY = String.raw`
import os, sys, zipfile
archive, dest = sys.argv[1], sys.argv[2]
root = os.path.realpath(dest)
with zipfile.ZipFile(archive) as z:
    for info in z.infolist():
        target = os.path.realpath(os.path.join(dest, info.filename))
        if os.path.commonpath([root, target]) != root:
            raise SystemExit("unsafe path in zip: " + info.filename)
        if info.is_dir():
            os.makedirs(target, exist_ok=True)
            continue
        os.makedirs(os.path.dirname(target), exist_ok=True)
        with z.open(info) as src, open(target, "wb") as out:
            while True:
                chunk = src.read(65536)
                if not chunk:
                    break
                out.write(chunk)
        mode = info.external_attr >> 16
        os.chmod(target, 0o755 if mode & 0o111 else 0o644)
`

function extract(file, directory, archive) {
  mkdirSync(directory, { recursive: true })
  if (archive === 'tar.gz') {
    const tar = spawnSync('tar', ['-xzf', file, '-C', directory], { encoding: 'utf8' })
    if (tar.status !== 0) throw new Error(`tar failed: ${tar.stderr}`)
    return
  }
  const unzip = spawnSync('unzip', ['-q', '-o', file, '-d', directory], { encoding: 'utf8' })
  if (unzip.status === 0) return
  const python = spawnSync('python3', ['-c', ZIP_PY, file, directory], { encoding: 'utf8' })
  if (python.status !== 0) throw new Error(`cannot unzip: install unzip or python3 (${unzip.stderr || python.stderr})`)
}

function archivePath(root, component) {
  const extension = component.archive === 'zip' ? 'zip' : 'tar.gz'
  return join(root, 'tmp', `${component.name}-${component.version}.${extension}`)
}

function flatten(directory) {
  const entries = readdirSync(directory)
  if (entries.length === 1) {
    const only = join(directory, entries[0])
    try {
      if (statSync(only).isDirectory()) return only
    } catch {}
  }
  return directory
}

function writeLauncher(file, body) {
  mkdirSync(dirname(file), { recursive: true })
  writeFileSync(file, `#!/bin/sh\n${LAUNCHER_TAG}\n${body}\n`)
  chmodSync(file, 0o755)
}

function launcherBody(root, realPath) {
  return [
    `export JAVA_HOME="${join(root, 'jdk', 'current')}"`,
    `export GRADLE_USER_HOME="${join(root, 'gradle-home')}"`,
    `if [ -d "${join(root, 'sdk', 'current')}" ]; then export ANDROID_HOME="${join(root, 'sdk', 'current')}"; export ANDROID_SDK_ROOT="$ANDROID_HOME"; fi`,
    `if [ -d "${join(root, 'ndk', 'current')}" ]; then export ANDROID_NDK_HOME="${join(root, 'ndk', 'current')}"; fi`,
    `exec "${realPath}" "$@"`,
  ].join('\n')
}

function findIn(directory, tool) {
  for (const candidate of [join(directory, 'bin', tool), join(directory, tool), join(directory, 'bin', `${tool}.sh`)]) {
    if (existsSync(candidate)) return candidate
  }
  return null
}

export function writeSharedEnv(root) {
  const file = join(root, 'bin', 'env.sh')
  mkdirSync(dirname(file), { recursive: true })
  writeFileSync(
    file,
    [
      '# source this file to get the shared toolchain in any shell',
      `export DSH_ANDROID_ROOT="${root}"`,
      `export JAVA_HOME="${join(root, 'jdk', 'current')}"`,
      `export GRADLE_USER_HOME="${join(root, 'gradle-home')}"`,
      `[ -d "${join(root, 'sdk', 'current')}" ] && export ANDROID_HOME="${join(root, 'sdk', 'current')}" && export ANDROID_SDK_ROOT="$ANDROID_HOME"`,
      `[ -d "${join(root, 'ndk', 'current')}" ] && export ANDROID_NDK_HOME="${join(root, 'ndk', 'current')}"`,
      `case ":$PATH:" in *:"${join(root, 'bin')}":*) ;; *) export PATH="${join(root, 'bin')}:$PATH" ;; esac`,
      '',
    ].join('\n'),
  )
  chmodSync(file, 0o644)
}

function installToolLaunchers(root, manifest, { noLink = false } = {}) {
  const link = (tool, real) => {
    writeLauncher(binPath(root, tool), launcherBody(root, real))
    if (noLink) return
    // Shared PATH convenience: a plain `java` / `gradle` works in any session
    // shell without sourcing env.sh. Never written for containers/CI.
    try {
      writeLauncher(join('/usr/local/bin', tool), launcherBody(root, real))
    } catch {}
  }
  const jdk = currentPath(root, 'jdk')
  for (const tool of ['java', 'javac', 'jar']) {
    const real = join(jdk, 'bin', tool)
    if (existsSync(real)) link(tool, real)
  }
  const gradle = findIn(currentPath(root, 'gradle'), 'gradle')
  if (gradle) link('gradle', gradle)
  for (const component of enabledComponents(manifest)) {
    for (const tool of component.provides ?? []) {
      const real = findIn(currentPath(root, component.name), tool)
      if (real) link(tool, real)
    }
  }
  writeSharedEnv(root)
}

/** Package CLIs (broker, provision, build, status, doctor) into shared bin + /usr/local/bin. */
function installPackageLaunchers(root, { noLink = false } = {}) {
  // A checkout that provisioned once must not hijack the machine-wide
  // launchers: /usr/local/bin is what the MCP entry resolves through PATH.
  const linkGlobal = !noLink && isInstalledCopy(PKG_DIR, PKG.name)
  for (const [tool, relative] of Object.entries(PKG.bin ?? {})) {
    const real = join(PKG_DIR, relative)
    if (!existsSync(real)) continue
    const body = `exec "${process.execPath}" "${real}" "$@"`
    writeLauncher(binPath(root, tool), body)
    if (!linkGlobal) continue
    try {
      writeLauncher(join('/usr/local/bin', tool), body)
    } catch {
      // /usr/local/bin is not writable in every deployment; PATH may still
      // reach <root>/bin through android-env.sh.
    }
  }
}

function writeGradleUserHome(root, manifest) {
  const home = join(root, 'gradle-home')
  mkdirSync(home, { recursive: true })
  const file = join(home, 'gradle.properties')
  if (existsSync(file)) return // never overwrite a hand-tuned file
  const lines = ['# generated by dsh-android-toolchain; safe to edit (kept on re-provision)']
  for (const [key, setting] of Object.entries(manifest.gradleUserHome ?? {})) lines.push(`${key}=${setting}`)
  writeFileSync(file, `${lines.join('\n')}\n`)
}

export async function installComponent(root, component, { allowUnpinned = false, dryRun = false, reuseArchive = null } = {}) {
  const target = join(root, component.name, component.version)
  const marker = installedMarker(root, component.name, component.version)
  if (existsSync(marker)) return { name: component.name, version: component.version, skipped: true }
  if (!component.source) throw new Error(`${component.name}: no source in the manifest`)
  if (!/^[0-9a-f]{64}$/.test(component.sha256 ?? '') && !allowUnpinned) {
    throw new Error(`${component.name}: sha256 is not pinned; run --pin --write, or pass --allow-unpinned`)
  }
  if (dryRun) return { name: component.name, version: component.version, planned: true, source: component.source }

  const tmp = join(root, 'tmp')
  mkdirSync(tmp, { recursive: true })
  const archiveFile = archivePath(root, component)
  const extractDir = join(tmp, `extract-${component.name}-${component.version}`)
  rmSync(extractDir, { recursive: true, force: true })
  let reused = false
  let reusedFrom = null
  let actual = ''
  let bytes = 0
  if (existsSync(archiveFile)) {
    const cached = await sha256(archiveFile)
    if (component.sha256 && cached === component.sha256) {
      actual = cached
      bytes = statSync(archiveFile).size
      reused = true
    } else {
      rmSync(archiveFile, { force: true })
    }
  }
  // A second root on the same device should not download the same 350 MB again:
  // copy the other root's archive when it matches the pin byte for byte.
  if (!reused && reuseArchive && existsSync(reuseArchive)) {
    const cached = await sha256(reuseArchive)
    if (!component.sha256 || cached === component.sha256) {
      copyFileSync(reuseArchive, archiveFile)
      actual = cached
      bytes = statSync(archiveFile).size
      reused = true
      reusedFrom = reuseArchive
    }
  }
  if (!reused) {
    const downloaded = await download(component.source, archiveFile)
    actual = downloaded.sha256
    bytes = downloaded.bytes
  }
  if (component.sha256 && actual !== component.sha256) {
    rmSync(archiveFile, { force: true })
    throw new Error(`${component.name}: sha256 mismatch\n  expected ${component.sha256}\n  actual   ${actual}`)
  }
  extract(archiveFile, extractDir, component.archive)
  const payload = flatten(extractDir)
  mkdirSync(dirname(target), { recursive: true })
  rmSync(target, { recursive: true, force: true })
  try {
    renameSync(payload, target)
  } catch {
    const copied = spawnSync('cp', ['-a', payload, target], { encoding: 'utf8' })
    if (copied.status !== 0) throw new Error(`cannot move payload into ${target}: ${copied.stderr}`)
  }
  writeFileSync(
    marker,
    JSON.stringify({ name: component.name, version: component.version, source: component.source, sha256: actual, bytes, installedAt: new Date().toISOString(), ...(reusedFrom ? { reusedFrom } : {}) }, null, 2),
  )
  const current = currentPath(root, component.name)
  rmSync(current, { force: true })
  symlinkSync(component.version, current)
  rmSync(extractDir, { recursive: true, force: true })
  rmSync(archiveFile, { force: true })
  return { name: component.name, version: component.version, installed: true, bytes, reusedFrom }
}

async function verifyManifest({ strict }) {
  const manifest = load()
  const { problems, warnings } = validateManifest(manifest, { strict })
  for (const warning of warnings) console.warn(`warn: ${warning}`)
  for (const problem of problems) console.error(`problem: ${problem}`)
  const probes = await probeSources(manifest)
  for (const probe of probes) {
    console.log(`${probe.ok ? 'ok  ' : 'FAIL'} ${probe.name} ${probe.status || probe.error || ''}`)
  }
  if (strict && probes.some((probe) => !probe.ok)) fail('at least one source is unreachable')
  if (problems.length) process.exit(1)
  log(`manifest ok (${probes.length} enabled component(s))`)
}

async function pin({ write }) {
  const manifest = load()
  const hashes = {}
  const root = resolveRoot({ create: true })
  for (const component of enabledComponents(manifest)) {
    if (!component.source) continue
    mkdirSync(join(root, 'tmp'), { recursive: true })
    const file = archivePath(root, component)
    const { sha256: digest, bytes } = await download(component.source, file)
    // Keep the archive when writing the manifest: the next install reuses it
    // instead of downloading the same 350 MB twice.
    if (!write) rmSync(file, { force: true })
    hashes[component.name] = digest
    console.log(`${component.name} ${component.version} ${digest} (${Math.round(bytes / 1e6)} MB)`)
  }
  if (!write) return
  for (const [name, digest] of Object.entries(hashes)) manifest.components[name].sha256 = digest
  const target = MANIFEST ?? MANIFEST_PATH
  writeFileSync(target, `${JSON.stringify(manifest, null, 2)}\n`)
  log(`manifest updated: ${typeof target === 'string' ? target : fileURLToPath(target)}`)
}

async function main() {
  if (has('--verify-manifest')) return verifyManifest({ strict: has('--strict') })
  if (has('--pin')) return pin({ write: has('--write') })

  const auto = has('--auto')
  if (auto) {
    if ((process.env.DSH_ANDROID_PROVISION ?? '').toLowerCase() === 'off') return log('provisioning disabled by DSH_ANDROID_PROVISION=off')
    if (process.env.CI) return log('CI detected: skipping provisioning (run android-provision on the device)')
  }

  const primary = resolveRoot({})
  const root = resolveRoot({ root: value('--root'), create: true })
  const manifest = load()
  const selected = values('--component')
  const unknown = selected.filter((name) => !manifest.components?.[name])
  if (unknown.length) fail(`unknown component(s): ${unknown.join(', ')}; manifest has: ${Object.keys(manifest.components ?? {}).join(', ')}`)
  const dryRun = has('--dry-run')
  const allowUnpinned = has('--allow-unpinned')
  const todo = enabledComponents(manifest).filter((component) => selected.length === 0 || selected.includes(component.name))

  const reuseFrom = value('--reuse-from')
  const reuseRoot = reuseFrom ? resolveRootRef(reuseFrom, { primary }) : null

  log(`root: ${root}${dryRun ? ' (dry run)' : ''}`)
  if (reuseRoot) log(`reusing archives from: ${reuseRoot}`)
  const noLink = has('--no-link')
  if (!dryRun) {
    writeGradleUserHome(root, manifest)
    installPackageLaunchers(root, { noLink })
  }

  let failures = 0
  for (const component of todo) {
    try {
      const outcome = await installComponent(root, component, {
        allowUnpinned,
        dryRun,
        reuseArchive: reuseRoot ? archivePath(reuseRoot, component) : null,
      })
      const state = outcome.skipped ? 'already installed' : outcome.planned ? 'would install' : `installed${outcome.reusedFrom ? ` (reused ${outcome.reusedFrom})` : ''}`
      log(`${component.name}@${component.version}: ${state}`)
    } catch (error) {
      failures += 1
      console.error(`[android-toolchain] ${error?.message ?? error}`)
    }
  }
  if (has('--register') && !dryRun) {
    const registered = registerRoot(primary, { path: root, label: value('--label') })
    log(`registry: ${registered.file} (${registered.already ? 'already registered' : 'added'} "${registered.label}" -> ${registered.path})`)
  }
  if (!auto && !dryRun) {
    installToolLaunchers(root, manifest, { noLink })
    log(`launchers: ${join(root, 'bin')}`)
  }
  if (failures) {
    if (auto) log(`${failures} component(s) failed; run android-provision to retry`)
    else process.exit(1)
  }
}

if (process.argv[1]?.endsWith('android-provision.mjs')) {
  await main()
}
